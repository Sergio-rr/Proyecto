    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            // Se captura cada uno de los campos
            int codigo = Integer.parseInt(txtCodigo.getText().trim());
            String nombre = txtNombre.getText().trim();
            int cantidad = Integer.parseInt(txtCantidad.getText().trim());
            double precio = Double.parseDouble(txtPrecio.getText().trim());

            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "El nombre no puede estar vacío.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Se valida si el nombre está compuesto unicamente por numeros
            if (nombre.matches("^\\d+$")) {
                JOptionPane.showMessageDialog(this, "El nombre no puede estar compuesto únicamente por números.", "Error de validación", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String catSeleccionada = cbCategoria.getSelectedItem().toString();// Gestion de la categoría seleccionada

            if (catSeleccionada.equals("--Nueva categoria--")) {
                String nuevaCat = JOptionPane.showInputDialog(this, "Ingrese el nombre de la nueva categoría:");
                if (nuevaCat != null && !nuevaCat.trim().isEmpty()) {
                    inv.NueCat(nuevaCat.trim()); // Agrega la categoría a la lista del inventario
                    catSeleccionada = nuevaCat.trim();
                } else {
                    return; // Si cancela o deja vacío, se detiene el proceso
                }
            }

            inv.insertar(codigo, nombre, cantidad, precio, catSeleccionada);
            JOptionPane.showMessageDialog(this, "Componente registrado correctamente.");

            this.dispose();// Se cierra la ventana de inserción

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Verifique que Codigo, Cantidad y Precio sean valores numericos validos.",
                "Error de formato: ",
                JOptionPane.ERROR_MESSAGE);
        }
        catch (IllegalArgumentException e) {
            // Aquí se mostrará exactamente el mensaje de la validación que haya fallado
            JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Error de validación",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    
